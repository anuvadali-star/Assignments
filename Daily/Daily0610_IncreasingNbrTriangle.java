package dailyassignments;

public class Daily0610_IncreasingNbrTriangle {

	public static void main(String[] args) {
		int num=1;
		int original=num;
		
		
		for(int i=1;i<=5;i++)//1
	    			
		{
			 num=original;
			 for(int j=1;j<=i;j++)//1
			 
		   {
		     System.out.print(num +" ");
		     num++;   	     
		   }
      
		
		System.out.println();
		
		 
	}
		
}
}